"""The ``iris-genui`` skill: where it lives, how it is registered, and how ``references/library.md`` is generated.

``library.md`` is the full component prompt, generated from the library JSON so it can never disagree with what the
validator accepts. ``tools/build_skill_refs.py`` rewrites it; a test fails when the checked-in file is stale.
"""

from __future__ import annotations

from pathlib import Path

from ..openui.prompt import PromptOptions, generate_system_prompt
from . import catalog

SKILL_NAME = "iris-genui"
SKILL_DIR = Path(__file__).resolve().parent.parent / "skills" / SKILL_NAME
SKILL_DESCRIPTION = "Show native displays in the Iris app with the iris_ui tool, written in OpenUI Lang."

STUDY_SKILL_NAME = "iris-study"
STUDY_SKILL_DIR = SKILL_DIR.parent / STUDY_SKILL_NAME
STUDY_SKILL_DESCRIPTION = "Study the person's work and propose a profile, templates and reply kits for them to review in Iris."

REFINE_SKILL_NAME = "iris-refine"
REFINE_SKILL_DIR = SKILL_DIR.parent / REFINE_SKILL_NAME
REFINE_SKILL_DESCRIPTION = "Refine the person's displays from how they were used: propose changes, new templates and retirements for them to review in Iris."

PREAMBLE = (
    "This is the component library for the iris_ui tool. Pass the program as the `code` argument; your reply itself "
    "stays ordinary text, and `fallback` carries the same content as Markdown. The rules below describe the language "
    "the program is written in."
)

RULES = [
    "The program is the `code` argument of iris_ui, not your reply. Reply in text as usual.",
    "Every statement must be reachable from root, or iris_ui rejects the program and tells you which.",
    "At most 60 statements, 12 KB of source, 8 levels of nesting and 2 KB per string.",
]

HEADER = (
    "# Iris component library\n\n"
    "<!-- Generated by tools/build_skill_refs.py from catalog/v1.library.json. Do not edit by hand. -->\n\n"
)


def render_library_md() -> str:
    options = PromptOptions(bindings=True, preamble=PREAMBLE, additional_rules=RULES)
    return HEADER + generate_system_prompt(catalog.v1(), options) + "\n"


def library_md_path() -> Path:
    return SKILL_DIR / "references" / "library.md"
